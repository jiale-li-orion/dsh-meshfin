#!/usr/bin/env node
/**
 * Emit `cordis.patch.yml` from the preset compositions under `presets/`.
 *
 * The compositions stay authored as the per-preset Cordis entry lists this
 * distribution has always shipped (one `agent.cordis.yml` per preset, with its
 * comments intact); upstream 0.2.1-rc.2 reads presets only as
 * `@deepseek-ai/dsh-agent-preset` declaration rows inside a bundle patch. This
 * script is that translation, so the mechanical part is reviewable and stays
 * testable instead of living in hand-edited YAML.
 *
 * Conversions applied to every composition:
 * - `name: ./<helper>.mjs` becomes `name: '@muwinds/dsh-anchored-presets/helpers/<helper>.mjs'`.
 *   A relative row resolves against the boot configuration directory (the
 *   profile), never an installed bundle, so the helpers ship as package
 *   subpaths of this package.
 * - `persona` rows move `text` to `prefix` (the 0.2.1 row config).
 * - `@deepseek-ai/dsh-workflow-worker-thread` becomes `@deepseek-ai/dsh-workflow-ptc`.
 * - `tool-subagent` rows lose `backgroundMode` and `enableRunInBackground`,
 *   which the 0.2.1 row rejects in favour of Agent Preset composition.
 *
 * Usage:
 *   node scripts/build-patch.mjs           # write cordis.patch.yml
 *   node scripts/build-patch.mjs --check   # exit 1 when the checked-in file differs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(dirname(fileURLToPath(import.meta.url)))
const packageName = '@muwinds/dsh-anchored-presets'

/** Preset directories in roster order: `presets/<directory>` is the composition source. */
const PRESETS = [
  'anchored-standard',
  'zero-anchored-standard',
  'whoami-standard',
  'prefab-anchored-standard',
  'eternal-minimal',
  'wire-think-standard',
  'combo-anchored-standard',
]

const HELPER_ROW = /^(\s*)name: \.\/([A-Za-z0-9._-]+\.mjs)\s*$/
const PERSONA_TEXT = /^(\s*)text: /
const DROPPED_ROW = /^(\s*)(backgroundMode|enableRunInBackground): /

/** Read one `key: value` scalar from a `preset.yml`. */
function presetField(text, key) {
  const match = new RegExp(`^${key}:\\s*(.*)$`, 'm').exec(text)
  return match === null ? undefined : match[1].trim()
}

/**
 * Convert one composition file's text.
 * @param text - the `agent.cordis.yml` contents.
 * @param file - diagnostic name.
 * @returns the converted composition text.
 */
export function convertComposition(text, file) {
  const out = []
  let rowId
  for (const line of text.split('\n')) {
    const row = /^- id: (\S+)\s*$/.exec(line)
    if (row !== null) rowId = row[1]
    if (DROPPED_ROW.test(line)) continue
    const helper = HELPER_ROW.exec(line)
    if (helper !== null) {
      out.push(`${helper[1]}name: '${packageName}/helpers/${helper[2]}'`)
      continue
    }
    if (rowId === 'persona' && PERSONA_TEXT.test(line)) {
      out.push(line.replace(PERSONA_TEXT, '$1prefix: '))
      continue
    }
    out.push(line.replaceAll('@deepseek-ai/dsh-workflow-worker-thread', '@deepseek-ai/dsh-workflow-ptc'))
  }
  const converted = out.join('\n')
  if (/name: \.\//.test(converted)) {
    throw new Error(`${file}: a relative plugin row survived conversion`)
  }
  void file
  return converted
}

/**
 * Build the declaration row for one preset.
 * @param directory - the `presets/` subdirectory.
 * @returns the patch row as text.
 */
function declarationRow(directory) {
  const base = join(here, 'presets', directory)
  const metadata = readFileSync(join(base, 'preset.yml'), 'utf8')
  const composition = convertComposition(readFileSync(join(base, 'agent.cordis.yml'), 'utf8'), directory)
  const id = presetField(metadata, 'id') ?? directory
  const name = presetField(metadata, 'name')
  const description = presetField(metadata, 'description')
  const order = presetField(metadata, 'order')
  const lines = [
    `    - id: preset-${id}`,
    "      name: '@deepseek-ai/dsh-agent-preset'",
    '      config:',
    `        id: ${id}`,
    ...name === undefined ? [] : [`        name: ${JSON.stringify(name)}`],
    ...description === undefined ? [] : [`        description: ${JSON.stringify(description)}`],
    ...order === undefined ? [] : [`        order: ${order}`],
    '        plugins:',
  ]
  // The composition is a top-level entry list; nesting it under `plugins:` shifts it by 10 columns.
  for (const line of composition.replace(/\n+$/, '').split('\n')) {
    lines.push(line === '' ? '' : `          ${line}`)
  }
  return `${lines.join('\n')}\n`
}

/** Render the complete bundle patch. */
export function renderPatch() {
  const header = [
    '# Generated by scripts/build-patch.mjs from presets/<id>/{agent.cordis.yml,preset.yml}.',
    '# Do not edit by hand: change the composition, then run `node scripts/build-patch.mjs`.',
    '#',
    '# One `@deepseek-ai/dsh-agent-preset` declaration per preset, row id `preset-<id>`.',
    '# Helper plugins ship as package subpaths of this bundle: a relative `name: ./x.mjs`',
    '# row resolves against the boot configuration directory (the profile), not an',
    '# installed bundle, so a preset mounted from an installed bundle cannot reach a',
    '# file that lives beside its own patch.',
    '- insert:',
  ].join('\n')
  const rows = PRESETS.map(directory => declarationRow(directory)).join('\n')
  return `${header}\n${rows}`
}

const check = process.argv.includes('--check')
const target = join(here, 'cordis.patch.yml')
const rendered = renderPatch()
if (check) {
  const current = readFileSync(target, 'utf8')
  if (current !== rendered) {
    console.error('scripts/build-patch.mjs: cordis.patch.yml is stale; rerun without --check')
    process.exitCode = 1
  } else {
    console.log('scripts/build-patch.mjs: cordis.patch.yml is current')
  }
} else {
  writeFileSync(target, rendered)
  console.log(`scripts/build-patch.mjs: wrote ${PRESETS.length} preset rows to ${target}`)
}
